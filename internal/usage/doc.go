// Package usage 是用量账本的读写与统计：把逐次调用的记录汇总成"按天 / 按模型 / 按会话"的报表，并计算费用。
//
// # 负责什么
//
//   - query.go：查询条件、聚合后的行（Row）、对事件列表的内存聚合（Memory 存储和测试用，SQLite 直接在 SQL 里聚合）；
//   - report.go：把行树形化（日 → 模型），按价格表计费，汇总总计；
//   - csv.go：导出原始记录；
//   - writer.go：异步写入——记账放在请求的收尾处，不能因为数据库慢而拖住对话。
//
// # 关键约定
//
//   - 账本只存 token 数和名称，**不存任何提示词或回答内容**；
//   - 输入 token 的口径统一为"含缓存读写"（见 provider.normalizeUsage），否则不同厂商的数字没法加总；
//   - 账本不存金额，费用在读取时按当前价格重算：价格填错了可以更正，历史花费同步改写；
//   - **没有价格的调用不计入花费，也不当作免费**，报表里单独统计有多少次没有价格；
//   - 订阅类厂商（ChatGPT 账号登录）按套餐额度而不是按量计费，只显示 token，不计金额；
//   - "请求数"只数成功的调用；失败的尝试（含已转交给其他成员的）单独统计，不算请求。
//
// # 在架构中的位置
//
// 依赖 provider（事件和用量的类型）。存储层（internal/store）实现 Source，Manager / App 用它出报表。
