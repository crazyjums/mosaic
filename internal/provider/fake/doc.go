// Package fake 是一个按脚本回复的"假厂商"，用于测试和离线演示。
//
// # 负责什么
//
//   - 按脚本（Script）逐步返回预设的思考、文本、工具调用、图片，像真实厂商一样以 Delta 流式输出；
//   - 内置 "demo" 脚本：思考 → 列目录 → 写文件（需确认）→ 执行命令（需确认）→ 带图片的总结；
//   - 内置 "echo" 脚本：原样复述用户输入，最简单的连通性测试；
//   - 支持从 JSON 文件加载自定义脚本（配置 options.script）。
//
// # 不负责什么
//
//   - 不理解对话内容。它只根据"本轮已经进行到第几步"来选择脚本中的下一步，
//     所以不管工具返回什么，它都按剧本往下走——这正是测试需要的确定性。
//
// # 在架构中的位置
//
// 适配层，与 openai、anthropic 平级，实现同一个 provider.Provider 接口，在 init() 中注册为 "fake" 类型。
// 内核的测试用它驱动完整的 agent 循环，不需要网络和密钥。
