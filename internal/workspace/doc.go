// Package workspace 提供工作区的环境信息（目前是 git 分支与是否有未提交改动），供状态栏显示。
//
// # 负责什么
//
// 在工作区目录执行只读的 git 命令（rev-parse、status --porcelain），汇总成 Info。
//
// # 不负责什么
//
//   - 不修改仓库，不给模型使用（模型要看 git 状态应该通过 shell 工具，走权限确认）；
//   - 不缓存：调用方（前端）自己决定刷新频率（每轮结束 + 定时）。
//
// # 为什么调用 git 命令而不是用 go-git 之类的库
//
// 只需要两条只读信息，命令行最简单、结果和用户在终端里看到的完全一致；
// 引入一个纯 Go 的 git 实现会显著增加依赖和二进制体积。没装 git 时返回 IsRepo=false，界面不显示这一项。
//
// # 在架构中的位置
//
// 适配层的小工具包，只被 internal/app 调用，不被内核依赖。
package workspace
