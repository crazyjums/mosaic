// Package skill 发现和读取"技能"（skill）：一个文件夹，里面有 SKILL.md（说明）和可选的资源文件。
//
// # 格式（与 Claude Code 的技能兼容）
//
//	<技能名>/SKILL.md
//	---
//	name: pdf-report            # 可省略，默认用文件夹名
//	description: 把数据整理成 PDF 报告。用户提到报告、PDF 时使用。
//	---
//	（正文：模型读到它之后照着做）
//	<技能名>/reference.md、scripts/…   # 资源文件，正文里引用，模型按需读取
//
// # 在哪里找（优先级从高到低，同名只取第一个）
//
//  1. <工作区>/.myllmapp/skills
//  2. <工作区>/.claude/skills
//  3. ~/.myllmapp/skills
//  4. ~/.claude/skills
//
// 项目里的技能优先于个人的；两种目录都支持，所以已经为 Claude Code 写好的技能可以直接用。
//
// # 怎么给模型用
//
// 系统提示词只列出名字和一句话简介（Prompt），正文不进上下文；模型觉得用得上、或用户在输入框里以 /技能名 开头时，
// 才通过 read_skill 工具读取正文（见 internal/tool/builtin/read_skill.go）。这样装很多技能也不占上下文。
//
// # 安全
//
// 技能文件夹里的内容是用户自己放进去的指令，但仍然限制读取范围：资源文件必须在该技能文件夹内
// （解析符号链接后再检查），大小有上限，二进制文件不返回。读取本身是只读操作；技能里让模型执行脚本时，
// 仍然要经过 shell 工具的权限确认。
//
// 本包只依赖标准库。
