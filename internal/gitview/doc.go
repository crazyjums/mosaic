// Package gitview 为界面上的“Git 窗口”提供只读的仓库信息：提交历史（含父子关系，用来画分支图）、
// 分支/标签、工作区变更、单个提交的文件列表与 diff。
//
// # 负责什么
//
// 在工作区目录执行 git 命令，把输出解析成结构化数据。所有数据都是只读的。
//
// # 不负责什么
//
//   - 不修改仓库：没有 commit、checkout、push、reset 等任何写操作。要改动仓库请让 agent 通过 shell 工具
//     去做（会走权限确认），或自己在终端里做；
//   - 不画图：分支图的“车道”布局在前端做（frontend/src/store/gitGraph.ts），这里只提供提交的父子关系；
//   - 不缓存：由前端决定何时刷新。
//
// # 安全
//
//   - 参数都是结构化的，从不拼接 shell 命令行；提交号只接受十六进制字符串，文件路径放在 “--” 之后，
//     不会被当作选项；
//   - 打开不受信任的仓库时，仓库自带的配置可能指定要执行的外部程序（core.fsmonitor、diff.external、
//     textconv 等）。这里用 -c 把它们关掉，并加 --no-ext-diff / --no-textconv；
//   - 设置 GIT_OPTIONAL_LOCKS=0：只读查看不要去抢 index 锁，免得和用户正在做的 git 操作冲突；
//   - 输出有大小上限、每次调用有超时。
//
// # 为什么调用 git 命令而不是 go-git
//
// 和 internal/workspace 同理：结果和用户在终端里看到的完全一致，不增加依赖和体积。没装 git 或不是仓库时返回明确的错误。
//
// # 在架构中的位置
//
// 适配层的小工具包，只被 internal/app 调用，不被内核依赖。
