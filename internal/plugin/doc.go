// Package plugin 是插件系统的预留扩展点（第一阶段只有接口，没有加载器）。
//
// # 计划支持的四类扩展
//
//   - Skill（技能）：一段按需加载的说明/提示词 + 可选的资源文件，模型在需要时"阅读"它；
//   - SlashCommand（斜杠命令）：用户在输入框里输入 /xxx 触发，可以展开为一段提示词或直接执行动作；
//   - Hook（钩子）：在固定的生命周期点（提交输入前、调用工具前后、一轮结束）运行，可以放行、拦截或改写；
//   - StatusLine（状态栏脚本）：根据当前状态生成状态栏文本，例如显示 git 分支、本月花费。
//
// # 与内核的关系（设计思路）
//
// 插件不直接修改内核，而是通过已有的扩展点接入：
//   - Hook 中的 PreToolUse 会在 core 的工具执行流程里、权限裁决之前调用（届时在 AgentConfig 中增加 Hooks 字段）；
//   - SlashCommand 由界面层（前端/CLI）解析，展开后的文本再交给 Engine.Send；
//   - Skill 以"列出可用技能 + read_skill 工具"的形式提供给模型；
//   - StatusLine 由 app 层定时调用，结果推给前端状态栏。
//
// 所有接口都只依赖标准库，方便以后支持"外部进程插件"（通过 JSON over stdio 实现同样的接口）。
// 详见 docs/roadmap.md。
