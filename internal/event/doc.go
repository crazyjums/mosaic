// Package event 定义"统一事件协议"和进程内的事件总线。
//
// # 负责什么
//
//   - 事件信封 Event（带协议版本号 Version）和每种事件的载荷（Payload）结构。
//   - 事件总线 Bus：内核把事件发布到总线，CLI、Wails 绑定层、测试等订阅者各取所需。
//
// # 不负责什么
//
//   - 不关心事件从哪个厂商来：厂商输出先由 internal/core 翻译成本包的事件。
//   - 不关心事件到哪里去：转发给前端是 internal/app 的事，打印到终端是 cmd/cli 的事。
//
// # 在架构中的位置
//
// 本包是整个项目最内层的契约，不依赖项目内任何其他包。
// 前端 frontend/src/protocol/events.ts 是本包的 TypeScript 镜像，两边必须同步修改，
// 协议的权威说明见 docs/event-protocol.md。
//
// 设计上把"事件"作为内核唯一的输出通道（命令接口见 core.Engine），好处是：
//  1. 界面与内核解耦：任何能消费 JSON 事件流的界面（桌面、终端、Web）都能接入；
//  2. 可回放：事件序列化成 JSONL 就是一份完整的调试记录，也能拿来驱动前端演示模式；
//  3. 可测试：断言"产生了哪些事件"比断言界面状态简单得多。
